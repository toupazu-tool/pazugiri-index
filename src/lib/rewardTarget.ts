// 報酬テンプレートが、共通部分（ノルマ・予定表・共有・あとで足すグラフ）に渡すデータの形
// どのイベントの形（交換所型・到達型…）でも、共通部分はこれだけを見て計算する
export type RewardTarget = {
  // 目標のポイント合計（交換所型：選んだ報酬の合計、到達型：目標にした報酬の到達ポイント）
  requiredTotal: number;
  // グラフに印を付けるための「◯ptでこれがもらえる」一覧。交換所型は空
  milestones: { label: string; points: number }[];
  // 目標の説明（到達型：「経験値の書・中（10,000pt）」）。保存画像などに出す。交換所型はなし
  goalLabel?: string;
};
